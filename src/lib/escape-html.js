/**
 * هروب HTML للقيم التي يتحكّم بها المستخدم قبل إدراجها في قوالب بريد Resend.
 *
 * لماذا: قوالب الإشعارات تُبنى بقوالب نصّية (template literals)، فأي قيمة خام
 * قادمة من نموذج عام يمكنها كسر بنية الجدول أو حقن وسوم — تزوير محتوى داخل
 * بريد داخلي يثق به المكتب. الهروب يحافظ على النص كما هو ويعرضه حرفيًا.
 *
 * ترتيب الاستبدال مقصود: `&` أولًا، وإلا تُرمَّز الكيانات الناتجة مرّتين
 * (مثال: `&` تصبح `&amp;amp;`).
 *
 * لا يحذف أي محتوى، ولا يمسّ النص العربي أو الإنجليزي أو علامات الترقيم
 * المشروعة — يحوّل خمسة محارف HTML حسّاسة فقط.
 *
 * @param {unknown} value
 * @returns {string}
 */
export function escapeHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
