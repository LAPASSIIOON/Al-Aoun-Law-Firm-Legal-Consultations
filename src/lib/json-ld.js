/**
 * تسلسل JSON-LD آمن للإدراج داخل <script type="application/ld+json">.
 *
 * لماذا لا يكفي JSON.stringify وحده: يهرّب هذا الأخير وفق قواعد JSON فقط
 * (" و \ ومحارف التحكّم)، و`<` محرف مشروع تمامًا داخل سلاسل JSON فلا يمسّه.
 * لكن محلّل HTML يعامل محتوى <script> كنصّ خام ويبحث عن التسلسل الحرفي
 * `</script` فيُنهي العنصر قبل أن يبدأ أي تحليل JSON — فيخرج ما بعده كوسوم
 * تُنفَّذ. لذا يكفي منع وصول `<` حرفيًا إلى محلّل HTML.
 *
 * `\u003c` تسلسل هروب JSON صالح: يعيده محلّل JSON إلى `<`، بينما لا يرى
 * محلّل HTML سوى محارف ASCII عادية — فلا تنتهي الوسم.
 *
 * لا نهرّب `>` (لا يُنهي عنصرًا وحده) ولا `&` (لا تُفكّ الكيانات داخل النصّ
 * الخام) ولا U+2028/2029 (خطرها في سياقات JS التنفيذية لا في ld+json الخامل).
 *
 * @param {unknown} value
 * @returns {string}
 */
export function jsonLdScript(value) {
  return JSON.stringify(value).replace(/</g, '\\u003c');
}
